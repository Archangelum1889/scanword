// «Тесный» укладчик (см. tight_spec.md). Отличие от Swedish/Dense:
// те ЗАПРЕЩАЮТ ставить букву впритык-параллельно без пересечения → между
// параллельными словами всегда «ров» пустых клеток. Тесный это РАЗРЕШАЕТ,
// но проверяет per-cell: каждый образовавшийся перпендикулярный ряд букв
// длиной ≥2 обязан быть словом банка (canPlaceTight), иначе reject.
// Валидные побочные ряды регистрируются как отдельные слова со своей
// клеткой-подсказкой (двойные H+V подсказки в одной клетке — сливаются).
// Пул включает длину 2 (старые движки её не берут) — короткие слова и
// сшивают клетки впритык. Формат JSON тот же {rows,cols,grid,words,wordCount}.
// Старые движки не трогаются.
function generatePuzzleTightDense(bank, opts) {
  opts = opts || {};
  var maxDim = opts.maxDim || 18;
  var wordCap = opts.wordCap || 100;
  var CHAR_CAP = opts.charCap || 550;
  var LEN_CAP = opts.lenCap || 900;

  // Пул: длины 2..11, дедуп по слову (первая встреченная подсказка выигрывает).
  var wordMap = new Map();
  bank.forEach(function (e) {
    if (!e || !e.w || e.w.length < 2 || e.w.length > 11) return;
    if (!wordMap.has(e.w)) wordMap.set(e.w, e);
  });
  var poolAll = Array.from(wordMap.values());
  if (!poolAll.length) return { rows: 0, cols: 0, grid: [], words: [], wordCount: 0 };
  var WORD_SET = new Set(poolAll.map(function (e) { return e.w; }));

  var byLen = {};
  poolAll.forEach(function (e) { (byLen[e.w.length] = byLen[e.w.length] || []).push(e); });
  Object.keys(byLen).forEach(function (L) {
    var arr = shuffle(byLen[L]);
    byLen[L] = arr.length > LEN_CAP ? arr.slice(0, LEN_CAP) : arr;
  });

  // char -> [{entry, idx}], капнуто ради производительности на большом банке.
  var byChar = new Map();
  shuffle(poolAll).forEach(function (e) {
    for (var i = 0; i < e.w.length; i++) {
      var ch = e.w[i];
      if (!byChar.has(ch)) byChar.set(ch, []);
      var b = byChar.get(ch);
      if (b.length < CHAR_CAP) b.push({ entry: e, idx: i });
    }
  });

  // --- состояние сетки ---
  var letters = new Map();     // "r,c" -> {char,h,v}
  var clueMap = new Map();     // "r,c" -> {H:slot|null, V:slot|null}
  var placed = [];             // {id, entry, r, c, dir, len}
  var placedIndex = new Map(); // "dir,r,c" -> текущий текст зарегистрированного там слова
  var usedWords = new Set();
  var minR = 0, maxR = 0, minC = 0, maxC = 0;

  function at(r, c) { return letters.get(key(r, c)); }
  function isClueCell(r, c) { return clueMap.has(key(r, c)); }

  function bboxWith(r0, c0, dir, len) {
    var cbR = dir === "H" ? r0 : r0 - 1, cbC = dir === "H" ? c0 - 1 : c0;
    var rr0 = Math.min(minR, cbR, r0), cc0 = Math.min(minC, cbC, c0);
    var rr1 = Math.max(maxR, dir === "H" ? r0 : r0 + len - 1);
    var cc1 = Math.max(maxC, dir === "H" ? c0 + len - 1 : c0);
    return { rows: rr1 - rr0 + 1, cols: cc1 - cc0 + 1 };
  }

  // Максимальный перпендикулярный ряд через (cr,cc), если там стоит newChar
  // (существующие соседи читаются из letters, сам newChar — гипотетически).
  function perpRun(cr, cc, newChar, dir) {
    var text = newChar, sR = cr, sC = cc;
    if (dir === "H") {
      var r = cr - 1, cell;
      while ((cell = at(r, cc))) { text = cell.char + text; sR = r; r--; }
      r = cr + 1;
      while ((cell = at(r, cc))) { text = text + cell.char; r++; }
    } else {
      var c = cc - 1, cellC;
      while ((cellC = at(cr, c))) { text = cellC.char + text; sC = c; c--; }
      c = cc + 1;
      while ((cellC = at(cr, c))) { text = text + cellC.char; c++; }
    }
    return { text: text, r: sR, c: sC };
  }

  // per-cell verification. null = reject; иначе {cross, sideNew:[...]}.
  function canPlaceTight(word, r, c, dir) {
    var len = word.length;
    var cbR = dir === "H" ? r : r - 1, cbC = dir === "H" ? c - 1 : c;
    if (at(cbR, cbC)) return null;                    // клетка-подсказка не может быть буквой
    var cbSlot = clueMap.get(key(cbR, cbC));
    if (cbSlot && cbSlot[dir]) return null;            // этот clue-слот в ЭТОМ направлении занят
    var aR = dir === "H" ? r : r + len, aC = dir === "H" ? c + len : c;
    if (at(aR, aC)) return null;                        // клетка сразу после конца — не буква

    var cross = 0, sideNew = [], seen = new Set(), seenWords = new Set();
    for (var i = 0; i < len; i++) {
      var cr = dir === "H" ? r : r + i, cc = dir === "H" ? c + i : c;
      var existing = at(cr, cc);
      if (existing) {
        if (existing.char !== word[i]) return null;
        if (dir === "H" && existing.h) return null;
        if (dir === "V" && existing.v) return null;
        cross++;
      } else if (isClueCell(cr, cc)) {
        return null;                                    // нельзя писать букву поверх clue-клетки
      }
      var perpDir = dir === "H" ? "V" : "H";
      var run = perpRun(cr, cc, word[i], dir);
      if (run.text.length >= 2) {
        var pKey = perpDir + "," + run.r + "," + run.c;
        if (seen.has(pKey)) continue;
        seen.add(pKey);
        if (placedIndex.has(pKey)) {
          // ряд уже кто-то занимает в этой позиции: НОВАЯ буква обязана
          // сохранить его текст неизменным — иначе это молчаливое
          // удлинение чужого слова (призрак), reject.
          if (placedIndex.get(pKey) !== run.text) return null;
          continue;
        }
        if (!WORD_SET.has(run.text)) return null;         // побочный ряд — не слово банка → reject
        if (usedWords.has(run.text) || seenWords.has(run.text)) return null; // слово уже занято
        var sClueR = perpDir === "V" ? run.r - 1 : run.r;
        var sClueC = perpDir === "V" ? run.c : run.c - 1;
        if (at(sClueR, sClueC)) return null;              // клетка-подсказка побочного слова — буква
        var sSlot = clueMap.get(key(sClueR, sClueC));
        if (sSlot && sSlot[perpDir]) return null;          // конфликт clue-слота
        var sEntry = wordMap.get(run.text);
        if (!sEntry) return null;
        seenWords.add(run.text);
        sideNew.push({ entry: sEntry, r: run.r, c: run.c, dir: perpDir, len: run.text.length, clueR: sClueR, clueC: sClueC });
      }
    }
    return { cross: cross, sideNew: sideNew };
  }

  function put(entry, r, c, dir, res) {
    var w = entry.w, len = w.length;
    for (var i = 0; i < len; i++) {
      var cr = dir === "H" ? r : r + i, cc = dir === "H" ? c + i : c;
      var k = key(cr, cc);
      var cell = letters.get(k);
      if (!cell) { cell = { char: w[i], h: false, v: false }; letters.set(k, cell); }
      if (dir === "H") cell.h = true; else cell.v = true;
      if (cr < minR) minR = cr; if (cr > maxR) maxR = cr;
      if (cc < minC) minC = cc; if (cc > maxC) maxC = cc;
    }
    var cbR = dir === "H" ? r : r - 1, cbC = dir === "H" ? c - 1 : c;
    if (cbR < minR) minR = cbR; if (cbR > maxR) maxR = cbR;
    if (cbC < minC) minC = cbC; if (cbC > maxC) maxC = cbC;
    var ck = key(cbR, cbC);
    if (!clueMap.has(ck)) clueMap.set(ck, { H: null, V: null });
    var id = placed.length + 1;
    clueMap.get(ck)[dir] = { text: entry.c, arrow: dir === "H" ? "right" : "down", wordId: id };
    placed.push({ id: id, entry: entry, r: r, c: c, dir: dir, len: len });
    placedIndex.set(dir + "," + r + "," + c, w);
    usedWords.add(w);

    (res && res.sideNew || []).forEach(function (s) {
      var sk = s.dir + "," + s.r + "," + s.c;
      if (placedIndex.has(sk) || usedWords.has(s.entry.w)) return; // защита от коллизий внутри put()
      if (s.clueR < minR) minR = s.clueR; if (s.clueR > maxR) maxR = s.clueR;
      if (s.clueC < minC) minC = s.clueC; if (s.clueC > maxC) maxC = s.clueC;
      var sck = key(s.clueR, s.clueC);
      if (!clueMap.has(sck)) clueMap.set(sck, { H: null, V: null });
      var sid = placed.length + 1;
      clueMap.get(sck)[s.dir] = { text: s.entry.c, arrow: s.dir === "H" ? "right" : "down", wordId: sid };
      placed.push({ id: sid, entry: s.entry, r: s.r, c: s.c, dir: s.dir, len: s.len });
      placedIndex.set(sk, s.entry.w);
      usedWords.add(s.entry.w);
    });
  }

  function tryApply(entry, r0, c0, dir) {
    if (usedWords.has(entry.w)) return null;
    var bw = bboxWith(r0, c0, dir, entry.w.length);
    if (Math.max(bw.rows, bw.cols) > maxDim) return null;
    var res = canPlaceTight(entry.w, r0, c0, dir);
    if (!res) return null;
    var shortBonus = entry.w.length === 2 ? 6 : (entry.w.length <= 4 ? 2 : 0);
    var curDim = Math.max(maxR - minR + 1, maxC - minC + 1);
    var growPenalty = Math.max(0, Math.max(bw.rows, bw.cols) - curDim);
    var score = res.cross * 6 + res.sideNew.length * 10 + shortBonus - growPenalty * 3 + Math.random() * 0.01;
    return { entry: entry, r: r0, c: c0, dir: dir, res: res, score: score };
  }

  // Сеем словом длины 4-7 в (0,1) горизонтально — клетка (0,0) под подсказку.
  var seedPool = poolAll.filter(function (e) { return e.w.length >= 4 && e.w.length <= 7; });
  if (!seedPool.length) seedPool = poolAll;
  put(shuffle(seedPool)[0], 0, 1, "H", null);

  var guard = 0, stall = 0, GUARD_MAX = wordCap * 10;
  while (placed.length < wordCap && guard++ < GUARD_MAX && stall < 10) {
    var best = null;

    // 1) Пересечения: растим от клеток-букв со свободным направлением.
    var frontier = [];
    letters.forEach(function (cell, k) { if (!cell.h || !cell.v) frontier.push(k); });
    if (frontier.length > 200) frontier = shuffle(frontier).slice(0, 200);
    for (var fi = 0; fi < frontier.length; fi++) {
      var parts = frontier[fi].split(","); var fr = Number(parts[0]), fc = Number(parts[1]);
      var fcell = letters.get(frontier[fi]);
      var need = [];
      if (!fcell.h) need.push("H");
      if (!fcell.v) need.push("V");
      var cands = byChar.get(fcell.char);
      if (!cands) continue;
      for (var ci = 0; ci < cands.length; ci++) {
        var cnd = cands[ci];
        if (usedWords.has(cnd.entry.w)) continue;
        for (var ni = 0; ni < need.length; ni++) {
          var d = need[ni];
          var r0 = d === "H" ? fr : fr - cnd.idx;
          var c0 = d === "H" ? fc - cnd.idx : fc;
          var got = tryApply(cnd.entry, r0, c0, d);
          if (got && (!best || got.score > best.score)) best = got;
        }
      }
    }

    // 2) Тесный параллельный рост: слово впритык к уже стоящему, без
    // пересечения — canPlaceTight сам проверит побочные перпендикулярные ряды.
    var anchors = placed.length > 32 ? shuffle(placed).slice(0, 32) : placed;
    for (var ai = 0; ai < anchors.length; ai++) {
      var an = anchors[ai];
      var lensSet = new Set([2, an.len - 1, an.len, an.len + 1].filter(function (L) { return L >= 2 && L <= 11; }));
      var lens = Array.from(lensSet);
      for (var oi = 0; oi < 2; oi++) {
        var off = oi === 0 ? -1 : 1;
        for (var li = 0; li < lens.length; li++) {
          var L = lens[li];
          var bucket = byLen[L];
          if (!bucket) continue;
          var sampleN = Math.min(bucket.length, 80);
          // Сдвиг близко к якорю (±3): самозамер показал, что расширение
          // диапазона до «касания одной клеткой впритык» (полный диапазон
          // -(L-1)..an.len-1) даёт длинные «шипы» — 1 клетка сшита, остальные
          // len-1 висят в пустоте; per-cell verification их пропускает
          // (валидны), но score предпочитал их обычным пересечениям (1
          // побочное слово дешевле найти, чем настоящий кроссинг), и грид
          // расползался вместо уплотнения (регресс 34.8%→42-50% пусто на
          // самозамере). Изоляционный штраф в tryApply не спас ситуацию —
          // проще держать диапазон у самого якоря, где overlap высокий.
          for (var si = -5; si <= 5; si++) {
            for (var bi = 0; bi < sampleN; bi++) {
              var be = bucket[bi];
              if (usedWords.has(be.w)) continue;
              var rr, cc2;
              if (an.dir === "H") { rr = an.r + off; cc2 = an.c + si; }
              else { rr = an.r + si; cc2 = an.c + off; }
              var got2 = tryApply(be, rr, cc2, an.dir);
              if (got2 && (!best || got2.score > best.score)) best = got2;
            }
          }
        }
      }
    }

    if (!best) { stall++; continue; }
    stall = 0;
    put(best.entry, best.r, best.c, best.dir, best.res);
  }

  // --- сборка выходного JSON (тот же формат, что у остальных движков) ---
  var bbRows = maxR - minR + 1, bbCols = maxC - minC + 1;
  var grid = [];
  for (var gr = 0; gr < bbRows; gr++) {
    var row = [];
    for (var gc = 0; gc < bbCols; gc++) row.push({ type: "blocked" });
    grid.push(row);
  }
  letters.forEach(function (cell, k) {
    var p = k.split(","); var rr = Number(p[0]) - minR, cc = Number(p[1]) - minC;
    grid[rr][cc] = { type: "letter", char: cell.char, wordIds: [] };
  });
  clueMap.forEach(function (slotPair, k) {
    var p = k.split(","); var rr = Number(p[0]) - minR, cc = Number(p[1]) - minC;
    if (grid[rr][cc].type === "letter") return; // защита — по построению не должно случаться
    grid[rr][cc] = { type: "clue", H: slotPair.H, V: slotPair.V };
  });
  var words = placed.map(function (p) {
    return { id: p.id, word: p.entry.w, clue: p.entry.c, dir: p.dir, r: p.r - minR, c: p.c - minC, len: p.len };
  });
  words.forEach(function (w) {
    for (var i = 0; i < w.len; i++) {
      var rr = w.dir === "H" ? w.r : w.r + i, cc = w.dir === "H" ? w.c + i : w.c;
      grid[rr][cc].wordIds.push(w.id);
    }
  });
  return { rows: bbRows, cols: bbCols, grid: grid, words: words, wordCount: words.length };
}

// Best-of-n по (blocked ↑, wordCount ↓, площадь bbox ↑); принимает ТОЛЬКО
// партии, прошедшие fullScanAssert против ТОГО ЖЕ bank, что подан на вход
// (не глобального WORD_BANK — тестовый/внешний банк может не совпадать).
function generatePuzzleTightBest(bank, n, opts) {
  opts = opts || {};
  var minWords = opts.minWords || 25;
  var best = null, bestScore = null;
  for (var i = 0; i < n; i++) {
    var p = generatePuzzleTightDense(bank, opts);
    if (!p || p.wordCount < minWords) continue;
    if (!fullScanAssert(p, bank)) continue;
    var blocked = 0;
    for (var r = 0; r < p.rows; r++) for (var c = 0; c < p.cols; c++) if (p.grid[r][c].type === "blocked") blocked++;
    var score = [blocked, -p.wordCount, p.rows * p.cols];
    if (!best || swScoreLess(score, bestScore)) { best = p; bestScore = score; }
  }
  return best || generatePuzzleTightDense(bank, opts);
}

